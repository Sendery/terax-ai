import type { BenchKind } from "@/modules/terminal/gl/engineSession";
import type { RendererFont } from "@/modules/terminal/gl/gridRenderer";
import {
  BENCH_KINDS,
  BENCH_SESSION_COUNTS,
  type BenchRun,
  DEFAULT_MEGABYTES,
  runBench,
} from "@/terminal-lab/lib/bench";
import {
  type EchoResult,
  type EchoTarget,
  measureEcho,
} from "@/terminal-lab/lib/echo";
import type { LabColors } from "@/terminal-lab/lib/useLabAppearance";
import {
  runXtermBench,
  type XtermBenchRun,
} from "@/terminal-lab/lib/xtermBench";

const ECHO_SAMPLES = 50;

export const TIMER_NOTE =
  "WebKit clamps performance.now() to 1 ms, so every timing is a distribution over many samples and single values carry +-1 ms.";

export type LabReport = {
  version: 1;
  startedAt: string;
  finishedAt: string | null;
  userAgent: string;
  devicePixelRatio: number;
  timerNote: string;
  engineAvailable: boolean;
  font: RendererFont;
  bench: BenchRun[];
  xtermBench: XtermBenchRun[];
  captures: { engine: boolean; xterm: boolean };
  runtime: Record<string, unknown>;
  idle?: Record<string, unknown>;
  echo: { engine: EchoResult | null; xterm: EchoResult | null };
  errors: string[];
};

export function emptyReport(
  engineAvailable: boolean,
  font: RendererFont,
): LabReport {
  return {
    version: 1,
    startedAt: new Date().toISOString(),
    finishedAt: null,
    userAgent: navigator.userAgent,
    devicePixelRatio: window.devicePixelRatio,
    timerNote: TIMER_NOTE,
    engineAvailable,
    font,
    bench: [],
    xtermBench: [],
    captures: { engine: false, xterm: false },
    runtime: {
      hardwareConcurrency: navigator.hardwareConcurrency,
      platform: navigator.platform,
      visibility: document.visibilityState,
      measurementNotes: [
        "Engine benchmarks include session setup; xterm flood timing starts after PTY creation and includes shell startup still in progress.",
        "xterm consumes the same Rust-generated bytes via pty_open with ONLCR disabled; shell echo and startup text are excluded.",
        "Rust encode counters, credit round-trip and rAF intervals do not separately isolate Channel serialization, JS decode/apply or GPU execution time.",
      ],
    },
    echo: { engine: null, xterm: null },
    errors: [],
  };
}

export type RunPlan = {
  stage: HTMLElement;
  font: RendererFont;
  colors: LabColors;
  megabytes: Record<BenchKind, [number, number]>;
  engine: EchoTarget | null;
  xterm: EchoTarget | null;
  onProgress: (report: LabReport, step: string) => void;
  autorun?: boolean;
};

function message(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

/** Every measurement of the contract's phase 1 list that the webview can take. */
export async function runAll(
  plan: RunPlan,
  report: LabReport,
): Promise<LabReport> {
  for (const kind of BENCH_KINDS) {
    for (const [slot, sessions] of BENCH_SESSION_COUNTS.entries()) {
      const megabytes =
        plan.megabytes[kind][slot] ?? DEFAULT_MEGABYTES[kind][slot];
      plan.onProgress(report, `bench ${kind} x${sessions}`);
      try {
        const run = await runBench(
          plan.stage,
          plan.font,
          plan.colors,
          kind,
          sessions,
          megabytes,
        );
        report.bench.push(run);
        if (run.error)
          report.errors.push(`bench ${kind} x${sessions}: ${run.error}`);
        if (run.timedOut)
          report.errors.push(`bench ${kind} x${sessions}: timed out`);
        if (run.decodeErrors > 0)
          report.errors.push(
            `bench ${kind} x${sessions}: ${run.decodeErrors} decode errors`,
          );
        if (run.rust.some((stats) => stats === null))
          report.errors.push(
            `bench ${kind} x${sessions}: Rust statistics missing`,
          );
      } catch (error) {
        report.errors.push(`bench ${kind} x${sessions}: ${message(error)}`);
      }
      plan.onProgress(report, `bench ${kind} x${sessions} done`);
      if (plan.autorun) {
        plan.onProgress(report, `xterm ${kind} x${sessions}`);
        try {
          const comparison = await runXtermBench(
            plan.stage,
            plan.font,
            kind,
            sessions,
            megabytes,
          );
          report.xtermBench.push(comparison);
          if (comparison.error)
            report.errors.push(
              `xterm ${kind} x${sessions}: ${comparison.error}`,
            );
        } catch (error) {
          report.errors.push(`xterm ${kind} x${sessions}: ${message(error)}`);
        }
      }
    }
  }
  report.echo.engine = await echoOf("engine", plan.engine, plan, report);
  report.echo.xterm = await echoOf("xterm", plan.xterm, plan, report);
  report.finishedAt = new Date().toISOString();
  plan.onProgress(report, "done");
  return report;
}

export async function echoOf(
  name: string,
  target: EchoTarget | null,
  plan: Pick<RunPlan, "onProgress">,
  report: LabReport,
): Promise<EchoResult | null> {
  if (!target) {
    report.errors.push(`echo ${name}: pane not ready`);
    return null;
  }
  plan.onProgress(report, `echo ${name}`);
  try {
    const result = await measureEcho(target, ECHO_SAMPLES);
    if (result.error) report.errors.push(`echo ${name}: ${result.error}`);
    if (result.count !== ECHO_SAMPLES || result.timeouts !== 0)
      report.errors.push(
        `echo ${name}: only ${result.count}/${ECHO_SAMPLES} samples, ${result.timeouts} timeouts`,
      );
    return result;
  } catch (error) {
    report.errors.push(`echo ${name}: ${message(error)}`);
    return null;
  }
}
